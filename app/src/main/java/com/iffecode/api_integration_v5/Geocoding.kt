package com.iffecode.api_integration_v5;

public class Geocoding {
    private String name;
    private double latitude;
    private double longitude;

    public Geocoding() {
    }

    public String getName() {
        return name;
    }

    public double getLatitude() {
        return latitude;
    }

    public double getLongitude() {
        return longitude;
    }
}
